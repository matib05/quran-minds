/**
 * Build-time generator for the local Qur'an dataset.
 *
 * Inputs (both already present in this repo, both from Tanzil.net):
 *   resources/quran-text.txt  - "juz|surahName|surah|ayah|text" (Uthmani Minimal edition)
 *   resources/quran-data.js   - Tanzil Quran Metadata v1.0 (CC BY 3.0)
 *
 * Output:
 *   lib/quran/data/uthmani.js  - 6236 ayah strings, indexed by global ayah index
 *   lib/quran/data/meta.js     - surah / juz / hizb / rub / page / ruku / manzil / sajda tables
 *
 * They are emitted as ES modules rather than .json so the same import works in
 * webpack, vitest and plain `node` (which requires import attributes for JSON).
 *
 * The juz column inside quran-text.txt is NOT used: it is zero-indexed for
 * al-Faatiha and disagrees with Tanzil metadata on several juz boundaries.
 * All structural metadata is derived from resources/quran-data.js instead.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createContext, runInContext } from 'node:vm';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'lib/quran/data');

// --- load Tanzil metadata (plain script, not a module) -----------------------
const sandbox = {};
createContext(sandbox);
runInContext(readFileSync(resolve(root, 'resources/quran-data.js'), 'utf8'), sandbox);
const T = sandbox.QuranData;
if (!T?.Sura || !T?.Page || !T?.Juz) throw new Error('quran-data.js did not expose QuranData');

// --- load ayah text ---------------------------------------------------------
const lines = readFileSync(resolve(root, 'resources/quran-text.txt'), 'utf8')
  .split(/\r?\n/)
  .filter((l) => l.trim().length > 0);

if (lines.length !== 6236) throw new Error(`expected 6236 ayat, got ${lines.length}`);

const uthmani = new Array(6236);
const seen = new Map(); // "s:a" -> index
lines.forEach((line, i) => {
  const parts = line.split('|');
  if (parts.length < 5) throw new Error(`malformed line ${i + 1}`);
  const surah = Number(parts[2]);
  const ayah = Number(parts[3]);
  const text = parts.slice(4).join('|').trim();
  if (!text) throw new Error(`empty ayah at line ${i + 1}`);
  uthmani[i] = text;
  seen.set(`${surah}:${ayah}`, i);
});

// --- verify the text file's ordering matches Tanzil's sura offsets -----------
for (let s = 1; s <= 114; s++) {
  const [start, ayas] = T.Sura[s];
  for (let a = 1; a <= ayas; a++) {
    const idx = seen.get(`${s}:${a}`);
    if (idx !== start + a - 1) {
      throw new Error(`ayah ${s}:${a} is at index ${idx}, Tanzil metadata expects ${start + a - 1}`);
    }
  }
}

// --- build metadata ---------------------------------------------------------
const surahs = [];
for (let s = 1; s <= 114; s++) {
  const [start, ayas, order, rukus, nameAr, translit, nameEn, type] = T.Sura[s];
  surahs.push({
    number: s,
    startIndex: start,
    ayahCount: ayas,
    revelationOrder: order,
    rukuCount: rukus,
    nameArabic: nameAr,
    nameTransliterated: translit,
    nameEnglish: nameEn,
    revelationPlace: type === 'Meccan' ? 'makkah' : 'madinah',
    bismillahPre: s !== 1 && s !== 9,
  });
}

/** Convert Tanzil's [sura, aya] boundary tables into global ayah start indexes. */
function boundaries(table, expectedCount, label) {
  const starts = [];
  for (let i = 1; i < table.length; i++) {
    const entry = table[i];
    if (!entry || entry.length < 2) continue;
    const [s, a] = entry;
    if (s === 115) break; // terminator row
    const idx = T.Sura[s][0] + a - 1;
    starts.push(idx);
  }
  if (starts.length !== expectedCount) {
    throw new Error(`${label}: expected ${expectedCount} boundaries, got ${starts.length}`);
  }
  for (let i = 1; i < starts.length; i++) {
    if (starts[i] <= starts[i - 1]) throw new Error(`${label}: boundaries not ascending at ${i + 1}`);
  }
  return starts;
}

const meta = {
  source: 'Tanzil.net Quran Metadata v1.0 (CC BY 3.0) + Tanzil Uthmani Minimal text',
  totalAyat: 6236,
  surahs,
  juzStarts: boundaries(T.Juz, 30, 'juz'),
  hizbQuarterStarts: boundaries(T.HizbQaurter, 240, 'hizb quarter'),
  manzilStarts: boundaries(T.Manzil, 7, 'manzil'),
  rukuStarts: boundaries(T.Ruku, 556, 'ruku'),
  pageStarts: boundaries(T.Page, 604, 'page'),
  sajdas: T.Sajda.filter((x) => x && x.length === 3).map(([s, a, kind]) => ({
    surah: s,
    ayah: a,
    index: T.Sura[s][0] + a - 1,
    obligatory: kind === 'obligatory',
  })),
};

mkdirSync(outDir, { recursive: true });
const banner = [
  '// GENERATED by scripts/build-quran-data.mjs - do not edit by hand.',
  '// Source: Tanzil.net Uthmani Minimal text + Tanzil Quran Metadata v1.0 (CC BY 3.0).',
  '',
].join('\n');

/** Named const then default export - an anonymous default trips eslint. */
const toModule = (name, value) =>
  `${banner}const ${name} = ${JSON.stringify(value)};\n\nexport default ${name};\n`;

writeFileSync(resolve(outDir, 'uthmani.js'), toModule('uthmani', uthmani));
writeFileSync(resolve(outDir, 'meta.js'), toModule('meta', meta));

const words = uthmani.reduce((n, t) => n + t.split(/\s+/).length, 0);
console.log(`quran data written: 6236 ayat, ${words} words, ${meta.pageStarts.length} pages, ` +
  `${meta.juzStarts.length} juz, ${meta.hizbQuarterStarts.length} rub, ${meta.sajdas.length} sajdas`);
